export type InvoiceStatus = "payee" | "envoyee" | "en_retard" | "brouillon";
export type PaymentMethodType =
  | "Mobile Money"
  | "Carte Bancaire"
  | "Carte de Crédit"
  | "Espèces (Cash / Liquidités)";

export type InvoiceType = "doit" | "avoir" | "proforma";

export interface InvoiceItem {
  id: string;
  description: string;
  quantity: number;
  unitPrice: number;
  totalHT: number;
  unit?: string; // Unité : MT, KG, ITEM, FORFAIT, VOYAGE, SAC, HEURE...
  currency?: string; // Devise de la ligne : FCFA, USD, EUR...
}

export interface Invoice {
  id: string;
  number: string;
  invoiceType?: InvoiceType; // "doit" (défaut) | "avoir" | "proforma"
  templateId?: string; // "tpl-1" | "tpl-2" | "tpl-3" | "tpl-4" | "custom"
  originalInvoiceRef?: string; // Référence de la facture d'origine (pour facture d'avoir)
  avoirReason?: string; // Motif de l'avoir (retour marchandise, rabais commercial...)
  proformaValidityDays?: number; // Validité de l'offre en jours (pour facture proforma)
  company?: CompanyProfile; // Profil entreprise émettrice
  companyName?: string;
  clientName: string;
  clientContactPerson?: string; // Personne de contact chez le client
  clientNif?: string; // NIF du client
  clientEmail: string;
  clientPhone: string;
  clientCity: string;
  clientAddress?: string;
  object?: string; // Objet de la facture
  issueDate: string;
  dueDate: string;
  status: InvoiceStatus;
  poNumber?: string; // N° Bon de Commande / PO NO. (ex: 4700795005)
  contractNumber?: string; // Contrat NR (ex: DA/LOG/149-15A...MO)
  vendorNumber?: string; // N° Fournisseur / WFP Vendor NO. (ex: 50045826)
  ltiNumber?: string; // N° LTI (ex: 7700776450/7700784099/7700780024)
  bankAccountRef?: string; // N° de compte bancaire
  subtotalHT: number; // Montant brut des lignes HT
  discountPercent?: number; // 1ère Remise commerciale en %
  discountAmount?: number; // Montant de la remise en FCFA
  secondDiscountPercent?: number; // 2ème Remise en cascade en % (calculée sur Net Commercial 1)
  secondDiscountAmount?: number; // Montant 2ème Remise en FCFA
  netCommercial1?: number; // 1er Net Commercial si multi-remises
  netCommercial?: number; // Brut - Remise(s)
  escomptePercent?: number; // Escompte de règlement en %
  escompteAmount?: number; // Montant de l'escompte en FCFA
  netFinancier?: number; // Net Commercial - Escompte
  advanceAmount?: number; // Acompte / Avance déduite en FCFA
  taxableHT?: number; // Montant HT imposable
  taxRate: number; // Taux TVA (19%, 18%, 0%...)
  taxAmount: number;
  totalTTC: number;
  precompteRate?: number; // Précompte fiscal (ex: 2%, 5%)
  precompteAmount?: number; // Montant du précompte en FCFA
  isbRate?: number; // ISB alias
  isbAmount?: number;
  consignationAmount?: number;
  netToPay?: number; // Net à payer réel (Total TTC - Précompte/ISB)
  paidAmount: number;
  paymentMethod: PaymentMethodType;
  paymentDetail?: string;
  items: InvoiceItem[];
}

export interface Client {
  id: string;
  name: string;
  contactPerson: string;
  email: string;
  phone: string;
  address?: string;
  city: string;
  country: string;
  totalBilled: number;
  invoicesCount: number;
  nif?: string;
  whatsapp?: string;
}

export interface CompanyProfile {
  id: string;
  name: string; // Raison sociale
  shortName?: string; // Sigle (ex: STS, ADT...)
  tagline?: string; // Slogan ou sous-titre
  logoUrl?: string; // Image/Logo uploadé ou URL (Optionnel)
  stampUrl?: string; // Image du vrai tampon/cachet physique officiel uploadé par l'entrepreneur
  nif?: string; // Numéro NIF (Optionnel)
  rccm?: string; // Registre de commerce (Optionnel)
  phone?: string; // Téléphone (Optionnel)
  email?: string; // Email (Optionnel)
  address?: string; // Adresse géographique (Optionnel)
  city?: string; // Ville (Optionnel)
  country?: string; // Pays (Optionnel)
  bankAccount?: string; // Coordonnées bancaires / RIB (Optionnel)
  signatory?: string; // Mention de signature (Optionnel)
  showStamp?: boolean; // Afficher le tampon/cachet sur la facture (Optionnel)
  invoiceTemplateId?: string; // Modèle actif : tpl-1, tpl-2, tpl-3, tpl-4, custom
  invoiceAccentColor?: string; // Couleur d'accentuation (hex)
  showStampOnInvoice?: boolean; // Afficher le cachet sur la facture émise
  showBankDetailsOnInvoice?: boolean; // Afficher RIB / Mobile Money en bas
  showLegalMentionsOnInvoice?: boolean; // Afficher NIF/RCCM/Arrêté de compte
  defaultPaymentMethod?: PaymentMethodType; // Mode de paiement par défaut choisi
  defaultPaymentDetail?: string; // Détails du mode de paiement par défaut
  defaultTaxRate?: number; // Taux de TVA par défaut variable choisi par l'utilisateur
  customTemplateFileName?: string; // Nom du gabarit personnalisé importé
  customTemplateMime?: string; // Type MIME du document importé
  customTemplateUrl?: string; // Data URL ou aperçu du gabarit personnalisé
  customInvoiceData?: Partial<Invoice>; // Données modifiables de la facture personnalisée importée
}

